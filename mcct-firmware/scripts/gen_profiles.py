"""Compile the reflow profiles (profiles/*.json) into C tables.

Usage: python gen_profiles.py <profiles dir> <config/user_config.h> <src/display/font.c> <out/profiles_gen.c>

Each JSON file (taken in file-name order, at most 3) looks like:

    {
      "name": "Sn63/Pb37 leaded",
      "label": "Pb",
      "waypoints": [
        { "temp_c": 150, "ramp_s": 90, "hold_s": 0 },
        ...
      ]
    }

"label" (up to 3 characters) is what the display shows when choosing the
profile; every character must exist in the display font. Temperatures must
lie within the target range of user_config.h. Ramps steeper than the plate
can plausibly follow only produce a warning: the firmware waits at each
waypoint until the plate gets there.
"""
import glob
import json
import os
import re
import sys

MAX_PROFILES = 3
MAX_WAYPOINTS_TOTAL = 64
STEEP_RATE_C_PER_S = 3.0


def fail(msg):
    sys.exit(f"gen_profiles: error: {msg}")


def read_define(path, name):
    with open(path) as f:
        m = re.search(rf"#define\s+{name}\s+(-?\d+)", f.read())
    if not m:
        fail(f"{name} not found in {path}")
    return int(m.group(1))


def read_font_chars(path):
    with open(path) as f:
        text = f.read()
    chars = set("0123456789")
    chars.update(re.findall(r"GLYPH\('(.)'", text))
    return chars


def load(path, tmin, tmax, font):
    with open(path) as f:
        try:
            p = json.load(f)
        except json.JSONDecodeError as e:
            fail(f"{path}: {e}")
    name = os.path.basename(path)
    label = p.get("label", "")
    if not 1 <= len(label) <= 3:
        fail(f"{name}: label must be 1..3 characters")
    bad = [c for c in label if c not in font]
    if bad:
        fail(f"{name}: label characters {bad} cannot be shown on the display")
    wps = p.get("waypoints")
    if not wps:
        fail(f"{name}: no waypoints")
    out = []
    prev = 25.0
    for i, w in enumerate(wps):
        try:
            t, r, h = float(w["temp_c"]), int(w["ramp_s"]), int(w.get("hold_s", 0))
        except (KeyError, ValueError, TypeError):
            fail(f"{name}: waypoint {i + 1} needs numeric temp_c and ramp_s (hold_s optional)")
        if not tmin <= t <= tmax:
            fail(f"{name}: waypoint {i + 1} temperature {t} outside {tmin}..{tmax} degC")
        if not 0 <= r <= 3600 or not 0 <= h <= 3600:
            fail(f"{name}: waypoint {i + 1} times must be 0..3600 s")
        rate = abs(t - prev) / r if r else float("inf")
        if t > prev and rate > STEEP_RATE_C_PER_S:
            print(f"gen_profiles: warning: {name} waypoint {i + 1} asks for {rate:.1f} degC/s")
        out.append((int(round(t * 10)), r, h))
        prev = t
    return p.get("name", name), label, out


def write_if_changed(path, text):
    """Rewrite only when the content changes, so make-style rebuilds stay incremental."""
    try:
        with open(path, newline="") as f:
            if f.read() == text:
                return
    except FileNotFoundError:
        pass
    with open(path, "w", newline="\n") as f:
        f.write(text)


def main():
    if len(sys.argv) != 5:
        fail("usage: gen_profiles.py <dir> <user_config.h> <font.c> <out.c>")
    src_dir, cfg, font_c, out = sys.argv[1:]
    tmin = read_define(cfg, "CFG_TARGET_MIN_C")
    tmax = read_define(cfg, "CFG_TARGET_MAX_C")
    font = read_font_chars(font_c)

    files = sorted(glob.glob(os.path.join(src_dir, "*.json")))
    if not files:
        fail(f"no profiles in {src_dir}")
    if len(files) > MAX_PROFILES:
        fail(f"at most {MAX_PROFILES} profiles, found {len(files)}")
    profiles = [load(f, tmin, tmax, font) for f in files]
    if sum(len(p[2]) for p in profiles) > MAX_WAYPOINTS_TOTAL:
        fail("too many waypoints in total")

    lines = ["/* Generated by scripts/gen_profiles.py from the JSON files in profiles/. Do not edit. */",
             '#include "control/profile.h"', "",
             f"const uint8_t __code profile_count = {len(profiles)};", "",
             "const waypoint_t __code profile_waypoints[] = {"]
    first = []
    for name, label, wps in profiles:
        first.append(sum(len(p[2]) for p in profiles[:len(first)]))
        lines.append(f"    /* {name} */")
        for t, r, h in wps:
            lines.append(f"    {{ {t}, {r}, {h} }},")
    lines += ["};", "", "const profile_t __code profiles[] = {"]
    for (name, label, wps), f0 in zip(profiles, first):
        lines.append(f'    {{ "{label}", {f0}, {len(wps)} }},   /* {name} */')
    lines += ["};", ""]
    write_if_changed(out, "\n".join(lines))
    print("gen_profiles: " + ", ".join(f"{label} ({len(w)} waypoints)" for _, label, w in profiles))


if __name__ == "__main__":
    main()
